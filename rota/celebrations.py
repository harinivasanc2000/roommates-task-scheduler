def celebration_for(roommate, chore, completion_count):
    messages = CATALOGUE.get(roommate.name.lower(), {}).get(chore.name)
    if not messages:
        messages = [
            f"Nice work, {roommate.name}! ✨ {chore.name} is done.",
            f"Another one sorted, {roommate.name}! 🌟 {chore.name} complete.",
            f"Household hero moment! 🙌 {roommate.name} finished {chore.name}.",
        ]
    return messages[(completion_count - 1) % len(messages)]
